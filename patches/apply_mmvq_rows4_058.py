#!/usr/bin/env python3
"""0.5.8: four rows a workgroup for the single-column IQ4_NL product on RDNA3.5

The single-column IQ4_NL product (the MoE down projection at one token) takes four output rows a workgroup instead of
two; each row keeps its lanes, sums and reduction. Down [2560, 10 experts] 58.0 -> 54.9 us a layer. Bitwise. (IQ3_S,
the gate / up, went the other way at two rows: 84 -> 90 us.)

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 1 hunks across 1 file(s).

Usage: python patches/apply_mmvq_rows4_058.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = '#define STRIX_MMVQ_RDNA35_ROWS 4'

EDITS = {
    os.path.join(tree, "ggml", "src", "ggml-cuda", "mmvq.cu"): [
        ('''#define STRIX_MMVQ_RDNA35_ROWS 2
''',
         '''#define STRIX_MMVQ_RDNA35_ROWS 4
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
