#!/usr/bin/env python3
"""XRES only while the combine's residual output outlives the mix that reads it (issue #7).

XRES (0.4.3) made the HC gate mix read the combine's F32 residual output, a dependency the graph does not record. The last layer's residual has no later reader, so the allocator could place the head mix's down projection output over it: with many outputs in one ubatch (llama-perplexity, -ub 512 / 2048) the head read its first 64 rows overwritten. The plan now keeps the F32 streams unless the residual is read again after the mix or is a graph output.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 3 hunks across 1 file(s).

Usage: python patches/apply_xres_fix_044.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'llama-perplexity at -ub 512 / 2048'

EDITS = {
    os.path.join(tree, "ggml", "src", "ggml-cuda", "ggml-cuda.cu"): [
        ('''    int nread = 0;
''',
         '''    int nread = 0, last_read = last;
'''),
        ('''        ++nread;
        if (g_hc_inject.node == t) {
''',
         '''        ++nread;
        last_read = n;
        if (g_hc_inject.node == t) {
'''),
        ('''    if (nread == 0) {
        return;
    }
    args.store_xn_f32 = false;
''',
         '''    if (nread == 0) {
        return;
    }
    if (formed) {
        // The mix then reads the combine's residual output, which the graph does not list among its inputs: it must
        // stay allocated until the mix has run - read again later (the next combine) or kept as an output. The last
        // layer's residual has neither, and the head's own down projection could be allocated over it: issue #7,
        // llama-perplexity at -ub 512 / 2048 read the first 64 rows of it overwritten by that GEMM's output
        const ggml_tensor * r = args.out_res->view_src ? args.out_res->view_src : args.out_res;
        bool alive = (r->flags & GGML_TENSOR_FLAG_OUTPUT) != 0;
        for (int n = last_read + 1; n < graph->n_nodes && !alive; ++n) {
            const ggml_tensor * t = graph->nodes[n];
            for (int s = 0; s < GGML_MAX_SRC && t->src[s]; ++s) {
                if (t->src[s] == r || t->src[s]->view_src == r) { alive = true; break; }
            }
        }
        if (!alive) {
            return;                         // the F32 streams stay
        }
    }
    args.store_xn_f32 = false;
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
