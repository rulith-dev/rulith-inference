#!/usr/bin/env python3
"""The disk tier's version 3 layout is numbered 4

A store keeps only its own format and deletes older entries at startup, so numbering the unchanged version 3 layout 4 drops what 0.2.7 and earlier wrote: 0.2.7 could compute a prompt chunk's attention densely over several conversations' cells, and the runs and checkpoints of such a conversation carry that on.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 3 hunks across 2 file(s).

Usage: python patches/apply_disk_store_v4_028.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'numbered 4 since 0.2.8'

EDITS = {
    os.path.join(tree, "tools", "server", "server-task.cpp"): [
        ('''const uint32_t SPC_V3 = 3;
''',
         '''// the version 3 layout, numbered 4 since 0.2.8 so that a store drops what earlier builds wrote: 0.2.7 could compute a
// prompt chunk's attention densely over several conversations' cells (qwen4exp_qsa_maskless_ok), and its runs and
// checkpoints of such a conversation carry that on
const uint32_t SPC_V3 = 4;
'''),
    ],
    os.path.join(tree, "tools", "server", "server-context.cpp"): [
        ('''                // version 3 where both contexts serve rows by position, else version 2; the store keeps no older one
''',
         '''                // version 3 where both contexts serve rows by position, else version 2; the store keeps no older one.
                // Version 3 is numbered 4 since 0.2.8 (see SPC_V3), so its entries from 0.2.7 and before go
'''),
        ('''                prompt_cache->set_disk(dir, mib ? std::max(1, atoi(mib)) : 16384, mctx != nullptr, tag, rows ? 3 : 2,
''',
         '''                prompt_cache->set_disk(dir, mib ? std::max(1, atoi(mib)) : 16384, mctx != nullptr, tag, rows ? 4 : 2,
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
