#!/usr/bin/env python3
"""The MTP draft scores the vocabulary through a low-rank pre-score and multiplies only the candidates' rows of the head exactly

A draft step read the whole LM head (338 MB IQ4_XS draft head, 521 MB Q6_K target head) for an argmax. With blk.N.nextn.lr_proj / lr_scores in the draft file (tools/make_draft_head.py --lowrank) a rank-512 Q8_0 pre-score (135 MB) picks 512 candidates; their rows of the target's own Q6_K head decide. The exact top-1 is among them 99.9-100% of the time (en / zh / held-out own chats), against 96.5-97% agreement of the IQ4_XS head. MTP decode +3.6% greedy, +4.9% sampled (acceptance 0.687 -> 0.702), greedy output identical. STRIX_MTP_LR_K sets the candidate count (0 = the full head).

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 7 hunks across 4 file(s).

Usage: python patches/apply_mtp_lowrank_head.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'QWEN4EXP_MTP_LR_RANK'

EDITS = {
    os.path.join(tree, "src", "llama-arch.h"): [
        ('''    LLM_TENSOR_NEXTN_SHARED_HEAD_HEAD,
    LLM_TENSOR_NEXTN_SHARED_HEAD_NORM,
''',
         '''    LLM_TENSOR_NEXTN_SHARED_HEAD_HEAD,
    LLM_TENSOR_NEXTN_LR_PROJ,
    LLM_TENSOR_NEXTN_LR_SCORES,
    LLM_TENSOR_NEXTN_SHARED_HEAD_NORM,
'''),
    ],
    os.path.join(tree, "src", "llama-arch.cpp"): [
        ('''    { LLM_TENSOR_NEXTN_SHARED_HEAD_HEAD,                 "blk.%d.nextn.shared_head_head" },
    { LLM_TENSOR_NEXTN_SHARED_HEAD_NORM,                 "blk.%d.nextn.shared_head_norm" },
''',
         '''    { LLM_TENSOR_NEXTN_SHARED_HEAD_HEAD,                 "blk.%d.nextn.shared_head_head" },
    { LLM_TENSOR_NEXTN_LR_PROJ,                          "blk.%d.nextn.lr_proj" },
    { LLM_TENSOR_NEXTN_LR_SCORES,                        "blk.%d.nextn.lr_scores" },
    { LLM_TENSOR_NEXTN_SHARED_HEAD_NORM,                 "blk.%d.nextn.shared_head_norm" },
'''),
        ('''    {LLM_TENSOR_NEXTN_SHARED_HEAD_HEAD,     {LLM_TENSOR_LAYER_REPEATING, GGML_OP_MUL_MAT}},
    {LLM_TENSOR_NEXTN_SHARED_HEAD_NORM,     {LLM_TENSOR_LAYER_REPEATING, GGML_OP_MUL}},
''',
         '''    {LLM_TENSOR_NEXTN_SHARED_HEAD_HEAD,     {LLM_TENSOR_LAYER_REPEATING, GGML_OP_MUL_MAT}},
    {LLM_TENSOR_NEXTN_LR_PROJ,              {LLM_TENSOR_LAYER_REPEATING, GGML_OP_MUL_MAT}},
    {LLM_TENSOR_NEXTN_LR_SCORES,            {LLM_TENSOR_LAYER_REPEATING, GGML_OP_MUL_MAT}},
    {LLM_TENSOR_NEXTN_SHARED_HEAD_NORM,     {LLM_TENSOR_LAYER_REPEATING, GGML_OP_MUL}},
'''),
    ],
    os.path.join(tree, "src", "llama-model.h"): [
        ('''    struct ggml_tensor * shared_head_head_in_s = nullptr;
    struct ggml_tensor * shared_head_norm      = nullptr;
''',
         '''    struct ggml_tensor * shared_head_head_in_s = nullptr;
    struct ggml_tensor * lr_proj               = nullptr; // strixllama: the draft's low-rank pre-score of the head
    struct ggml_tensor * lr_scores             = nullptr;
    struct ggml_tensor * shared_head_norm      = nullptr;
'''),
    ],
    os.path.join(tree, "src", "models", "qwen4exp.cpp"): [
        ('''#include "models.h"
#include "llama-impl.h"
''',
         '''#include "models.h"

#include <cmath>

// strixllama: rank of the draft head's low-rank pre-score (nextn.lr_proj / lr_scores)
static constexpr int64_t QWEN4EXP_MTP_LR_RANK = 512;
#include "llama-impl.h"
'''),
        ('''        layer.nextn.shared_head_head = create_tensor(tn(LLM_TENSOR_NEXTN_SHARED_HEAD_HEAD, "weight", il), { n_embd, n_vocab }, flags | TENSOR_NOT_REQUIRED);
    }
''',
         '''        layer.nextn.shared_head_head = create_tensor(tn(LLM_TENSOR_NEXTN_SHARED_HEAD_HEAD, "weight", il), { n_embd, n_vocab }, flags | TENSOR_NOT_REQUIRED);
        // strixllama: optional low-rank pre-score of the LM head for the draft (tools/make_draft_head.py --lowrank)
        layer.nextn.lr_proj   = create_tensor(tn(LLM_TENSOR_NEXTN_LR_PROJ,   "weight", il), { n_embd, QWEN4EXP_MTP_LR_RANK }, flags | TENSOR_NOT_REQUIRED);
        layer.nextn.lr_scores = create_tensor(tn(LLM_TENSOR_NEXTN_LR_SCORES, "weight", il), { QWEN4EXP_MTP_LR_RANK, n_vocab }, flags | TENSOR_NOT_REQUIRED);
    }
'''),
        ('''    cur = build_lora_mm(head_w, cur, head_s);
''',
         '''    // strixllama: the draft needs only the head's top tokens. With nextn.lr_proj / lr_scores in the draft file a
    // rank-512 pre-score over the vocabulary (Q8_0, 135 MB against the 338 MB IQ4_XS head) picks STRIX_MTP_LR_K
    // candidates, and only their rows of the head are multiplied exactly; every other token gets -inf. The draft
    // samples from the candidates and the target verifies as before, so outputs stay the target's
    static const int lr_k = getenv("STRIX_MTP_LR_K") ? atoi(getenv("STRIX_MTP_LR_K")) : 512;
    const int64_t nt = cur->ne[1];
    if (layer.nextn.lr_proj && layer.nextn.lr_scores && lr_k > 0 && head_s == nullptr && nt > 0) {
        ggml_tensor * q   = ggml_mul_mat(ctx0, layer.nextn.lr_proj, cur);                        // [rank, nt]
        ggml_tensor * sc  = ggml_mul_mat(ctx0, layer.nextn.lr_scores, q);                        // [n_vocab, nt]
        cb(sc, "mtp_lr_scores", -1);
        ggml_tensor * idx = ggml_top_k(ctx0, sc, lr_k);                                          // [K, nt]
        ggml_tensor * rows = ggml_get_rows(ctx0, head_w, ggml_reshape_1d(ctx0, idx, lr_k * nt)); // [n_embd, K*nt]
        rows = ggml_reshape_3d(ctx0, rows, n_embd, lr_k, nt);
        ggml_tensor * ex  = ggml_mul_mat(ctx0, rows, ggml_reshape_3d(ctx0, cur, n_embd, 1, nt)); // [K, 1, nt]
        ggml_tensor * full = ggml_fill(ctx0, sc, -INFINITY);
        cur = ggml_set_rows(ctx0, ggml_reshape_3d(ctx0, full, 1, sc->ne[0], nt), ggml_reshape_3d(ctx0, ex, 1, lr_k, nt), idx);
        cur = ggml_reshape_2d(ctx0, cur, sc->ne[0], nt);
    } else {
        cur = build_lora_mm(head_w, cur, head_s);
    }
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
