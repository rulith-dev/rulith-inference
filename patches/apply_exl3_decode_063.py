#!/usr/bin/env python3
"""0.6.3: EXL3 decode - dense products of up to 8 tokens through the GEMV

Dense EXL3 products of 2..8 tokens (the MTP verify step) took the tiled WMMA GEMM by crossovers measured before the
GEMV's 10-18 work (rotation loads, address space, wave interleave); the GEMV is now the faster one up to
MMH_GEMV_TOKENS whatever the number of 128-row groups: EXL3 4.05 MTP verify of 4 tokens qkv 172 -> 117 us, one
conversation 49.7 -> 52.7 tok/s (+6.1%), two +4.8%, four and eight even, acceptance equal. Single-token decode is
unchanged and bitwise; multi-token steps add in another order (fp16 input unscaled in the GEMV, scaled in the GEMM):
an agent run's 90,000 multi-token dense ops agree with the GEMM within 0.15%. STRIX_MMH_DENSE_GEMV=0 (dev): the old
crossovers.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 3 hunks across 1 file(s).

Usage: python patches/apply_exl3_decode_063.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'STRIX_MMH_DENSE_GEMV'

EDITS = {
    os.path.join(tree, "ggml", "src", "ggml-cuda", "mul-mat-had.cu"): [
        ('''// 16 rows; with few 128-row groups the GEMM also has few blocks (measured crossovers)
''',
         '''// 16 rows. strixllama 10-21: since the GEMV's rotation loads, address space and wave interleave work (10-18) it is the
// faster one up to MMH_GEMV_TOKENS whatever the groups (EXL3 4.05 MTP verify of 4 tokens: qkv 172 -> 117 us, the step
// 56.6 -> 51.3 ms, one conversation 49.7 -> 52.7 tok/s, two +4.8%, four and eight even; 90,000 ops of an agent run
// within 0.15% of the GEMM); the old crossovers (2 tokens: <= 64 groups, 3: 48, 4: 32, more: 16 or 2M weights) were
// measured before that
'''),
        ('''    if (tokens <= 1) {
        return true;
''',
         '''    // strixllama (dev): STRIX_MMH_DENSE_GEMV=0 takes the crossovers before 10-21
    static const bool old = getenv("STRIX_MMH_DENSE_GEMV") && atoi(getenv("STRIX_MMH_DENSE_GEMV")) == 0;
    if (old) {
        if (tokens <= 1) {
            return true;
        }
        if (tokens <= 2) {
            return groups <= 64;
        }
        if (tokens <= 3) {
            return groups <= 48;
        }
        if (tokens <= 4) {
            return groups <= 32;
        }
        return groups <= 16 || weights <= (1 << 21);
'''),
        ('''    if (tokens <= 2) {
        return groups <= 64;
    }
    if (tokens <= 3) {
        return groups <= 48;
    }
    if (tokens <= 4) {
        return groups <= 32;
    }
    return groups <= 16 || weights <= (1 << 21);
''',
         '''    return tokens <= MMH_GEMV_TOKENS;
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
