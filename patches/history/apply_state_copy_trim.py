#!/usr/bin/env python3
"""Copy the conv-state tails straight out of the concat, without a cont first

Each GDN layer keeps its conv history once per rollback slot (four with three draft tokens), and each copy went through a cont of the strided tail: 144 extra dispatches in a ~2500-dispatch 4-token verify pass. ggml_cpy reads a strided F32 source itself; the GDN conv fusion's matcher learns to accept the copy. Pure copies, so the output is bitwise the same; a verify pass measured 59.40 -> 58.90 ms.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 2 hunks across 2 file(s).

Usage: python patches/apply_state_copy_trim.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'the copy reads the strided tail itself'

EDITS = {
    os.path.join(tree, "src", "models", "qwen4exp.cpp"): [
        ('''        ggml_build_forward_expand(gf, ggml_cpy(ctx0, ggml_cont(ctx0, tail), dst));
''',
         '''        // strixllama: the copy reads the strided tail itself; a cont first was one more dispatch per slot, 144 of the
        // ~2500 in a 4-token verify pass
        ggml_build_forward_expand(gf, ggml_cpy(ctx0, tail, dst));
'''),
    ],
    os.path.join(tree, "ggml", "src", "ggml-cuda", "gdn-conv.cu"): [
        ('''        if (t->op == GGML_OP_CONT && t->src[0]->op == GGML_OP_VIEW && t->src[0]->view_src == cc) continue;
        return false;
''',
         '''        if (t->op == GGML_OP_CONT && t->src[0]->op == GGML_OP_VIEW && t->src[0]->view_src == cc) continue;
        // strixllama: the state update copies the tail straight out of the concat now, without a cont first
        if (t->op == GGML_OP_CPY && t->src[0]->op == GGML_OP_VIEW && t->src[0]->view_src == cc) continue;
        return false;
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
