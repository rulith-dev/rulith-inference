#!/usr/bin/env python3
"""0.5.7: a ubatch of consecutive tokens reads the batch's embedding rows where they are

llama_batch_allocr::ubatch_add zero-filled a copy of every embedding row of a ubatch and then copied the rows one
token at a time. The MTP draft's catch-up receives the target's hidden rows as embeddings, 40 KB a token, so an
8192-token prompt batch spent ~70 ms of one thread on 335 MB before its first catch-up pass while the GPU waited. A
ubatch whose tokens are consecutive in the batch now points into the batch's rows, as the whole-batch ubatch already
does; the batch outlives its ubatches. The catch-up of an 8192-token batch takes 185-229 -> ~120 ms (the GPU gap
before its first pass 85 -> 19 ms), about 1% of a prompt's time with MTP on. Bitwise; images, which are embedding
batches too, pass tools/vision_stress.py.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 3 hunks across 1 file(s).

Usage: python patches/apply_ubatch_embd_057.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'bool embd_in_place'

EDITS = {
    os.path.join(tree, "src", "llama-batch.cpp"): [
        ('''    const int64_t n_embd_all = batch.embd ? (int64_t) n_tokens*n_embd : 0;
''',
         '''    // strixllama: a ubatch of consecutive tokens of the batch reads their embedding rows where they are, as the
    // whole-batch ubatch does. Copied - after zero-filling the copy - the rows of an 8192-token MTP catch-up (40 KB a
    // token, 335 MB) took ~70 ms of one thread before its first pass. The batch outlives its ubatches
    bool embd_in_place = batch.embd != nullptr && !idxs.empty();
    for (size_t i = 1; embd_in_place && i < idxs.size(); ++i) {
        embd_in_place = idxs[i] == idxs[0] + (int32_t) i;
    }

    const int64_t n_embd_all = batch.embd && !embd_in_place ? (int64_t) n_tokens*n_embd : 0;
'''),
        ('''        if (batch.embd) {
''',
         '''        if (batch.embd && !embd_in_place) {
'''),
        ('''        /*.embd         =*/ batch.embd ? udata->embd.data() : nullptr,
''',
         '''        /*.embd         =*/ batch.embd ? (embd_in_place ? batch.embd + (int64_t) idxs[0]*n_embd : udata->embd.data()) : nullptr,
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
