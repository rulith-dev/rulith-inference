#!/usr/bin/env python3
"""--override-tensor accepts a device's host buffer type (ROCm_Host)

An integrated GPU computes on tensors in its pinned host buffers in place, so -ot can put weights in system memory outside the VRAM carve. Measured: 6 layers of experts (8 GB) moved to ROCm_Host at the 96 GB carve, prefill and decode unchanged (groundwork for a 64 GB carve).

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 1 hunks across 1 file(s).

Usage: python patches/apply_ot_host_buft.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = "also a device's host buffer type"

EDITS = {
    os.path.join(tree, "common", "arg.cpp"): [
        ('''            buft_list[ggml_backend_buft_name(buft)] = buft;
        }
''',
         '''            buft_list[ggml_backend_buft_name(buft)] = buft;
        }
        // strixllama: also a device's host buffer type (ROCm_Host). An integrated GPU computes on tensors in it in
        // place, so weights can be put in system memory outside the VRAM carve
        if (auto * host = ggml_backend_dev_host_buffer_type(dev)) {
            buft_list[ggml_backend_buft_name(host)] = host;
        }
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
