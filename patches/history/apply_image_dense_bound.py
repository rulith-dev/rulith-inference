#!/usr/bin/env python3
"""Dense sparse-attention inputs bounded once an image is in the conversation

Once a conversation holds an image, every later ubatch takes the dense sparse-attention inputs (a KQ mask and a per-block bias over n_kv x n_tokens, ~6.6 bytes a pair staged in pinned host memory). They grew with every image, and each time the pinned staging buffer grew, ROCm on Windows kept the old one: 27 images of 1920x1080 on a 58K conversation took 12 GiB of RAM, and a 14K text append at batch 8192 then faulted (issue #2). Such ubatches are now held to n_kv x n_tokens <= 2^27 (STRIX_DENSE_UBATCH_BUDGET), a compute buffer that has to grow again grows by at least a quarter, and a kernel fault names the failing node and where its tensors lie. Text before any image is unchanged, bitwise.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 3 hunks across 3 file(s).

Usage: python patches/apply_image_dense_bound.py [tree]
"""
