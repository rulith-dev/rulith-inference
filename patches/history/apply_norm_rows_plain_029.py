#!/usr/bin/env python3
"""Plain RMS norms over narrow rows run a wave per row

The per-head norms of the GDN and attention layers normalise rows of 128 floats; the generic rms_norm kernel gave each row a block. rms_rows_f32 (the gated norm's kernel) takes a no-weight variant, and rms_norm_f32_cuda hands it rows of at most 256 floats when there are at least 4096 of them: the q/k norms of a 64K-token prefill 449 -> 352 ms, bitwise.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 6 hunks across 3 file(s).

Usage: python patches/apply_norm_rows_plain_029.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'ggml_cuda_rms_rows_plain'

EDITS = {
    os.path.join(tree, "ggml", "src", "ggml-cuda", "norm-gated.cu"): [
        ('''template <bool GATE>
''',
         '''template <bool GATE, bool HAS_W = true>
'''),
        ('''            const float t = scale * x[col] * w[col];
''',
         '''            float t;
            if constexpr (HAS_W) { t = scale * x[col] * w[col]; } else { t = scale * x[col]; }
'''),
        ('''
void ggml_cuda_op_norm_gated(ggml_backend_cuda_context & ctx, const ggml_cuda_norm_gated_match & m) {
''',
         '''
// strixllama: a plain RMS norm of narrow rows (no weight after it, as the gated delta net's q/k norms): the same
// wave-per-row kernel. norm.cu's launch gives each row a 256-thread block, and at 393K rows of 128 (48 heads x 8192
// tokens) that is block-scheduling bound: ~10 ms a layer where the bytes take ~2
bool ggml_cuda_rms_rows_plain(const float * x, float * dst, int ncols, int64_t nrows, int64_t nchannels, int64_t nsamples,
        int64_t stride_row, int64_t stride_channel, int64_t stride_sample, float eps, cudaStream_t stream) {
    const int64_t total = nrows * nchannels * nsamples;
    if (!norm_rows_enabled() || ncols > 256 || ncols % 32 != 0 || total < 4096) return false;
    const dim3 grid((unsigned) ((total + 7) / 8)), block(256);
    const ggml_cuda_kernel_launch_params lp(grid, block, 0, stream);
    ggml_cuda_kernel_launch(rms_rows_f32<false, false>, lp, x, (const float *) nullptr, (const float *) nullptr, dst,
        ncols, nrows, nchannels, total, stride_row, stride_channel, stride_sample, eps);
    return true;
}

void ggml_cuda_op_norm_gated(ggml_backend_cuda_context & ctx, const ggml_cuda_norm_gated_match & m) {
'''),
    ],
    os.path.join(tree, "ggml", "src", "ggml-cuda", "norm-gated.cuh"): [
        ('''int  ggml_cuda_norm_rows_match_at(const ggml_cgraph * cgraph, int i, ggml_cuda_norm_gated_match & m);
''',
         '''int  ggml_cuda_norm_rows_match_at(const ggml_cgraph * cgraph, int i, ggml_cuda_norm_gated_match & m);
bool ggml_cuda_rms_rows_plain(const float * x, float * dst, int ncols, int64_t nrows, int64_t nchannels, int64_t nsamples,
        int64_t stride_row, int64_t stride_channel, int64_t stride_sample, float eps, cudaStream_t stream);
'''),
    ],
    os.path.join(tree, "ggml", "src", "ggml-cuda", "norm.cu"): [
        ('''#include "norm.cuh"
#include <cstdint>
''',
         '''#include "norm.cuh"
#include "norm-gated.cuh"
#include <cstdint>
'''),
        ('''        const int64_t stride_row, const int64_t stride_channel, const int64_t stride_sample, const float eps, cudaStream_t stream) {
    const dim3 blocks_num(nrows, nchannels, nsamples);
    if (ncols < 1024) {
        const dim3 block_dims(256, 1, 1);
''',
         '''        const int64_t stride_row, const int64_t stride_channel, const int64_t stride_sample, const float eps, cudaStream_t stream) {
    const dim3 blocks_num(nrows, nchannels, nsamples);
    // strixllama: narrow rows (the per-head norms) a wave each, 8 rows a block - bitwise this kernel's result
    if (ggml_cuda_rms_rows_plain(x, dst, ncols, nrows, nchannels, nsamples, stride_row, stride_channel, stride_sample, eps, stream)) {
        return;
    }
    if (ncols < 1024) {
        const dim3 block_dims(256, 1, 1);
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
