#!/usr/bin/env python3
"""The KQ mask reads the membership bits of a ubatch's sequences in one pass

Each sequence's first mask row tested every cell's membership bitset (256 bits, 32 bytes a cell), so a ubatch of several conversations read the window's bitsets once per conversation. The bits of the ubatch's sequences (up to 16, one cell array) are gathered in one pass, two bytes a cell, and the rows test those: the same decisions on the same cells. Four conversations over ~112K cells: the step's inputs 2.33 -> 1.75 ms. STRIX_KQ_MASK_CHECK=1 fills every mask the upstream way as well and compares byte for byte (0 of 900+ differed over several conversations, images and agents).

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 7 hunks across 1 file(s).

Usage: python patches/apply_kq_mask_seq_bits_030.py [tree]
"""
