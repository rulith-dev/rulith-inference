#!/usr/bin/env python3
"""0.5.9: an MTP draft context lets positions jump forward over a prompt's images

The MTP drafter skips the target's embedding batches (upstream's TODO: no token to draft from), so the draft
context never sees a prompt's image tokens and its positions jump over them. With M-RoPE (Qwen) the batch check
allows forward jumps; with plain RoPE (Nemotron 3.5 Super) it refused the next text batch and the request failed
(HTTP 500 on any image with MTP on). A context of type MTP now allows them too. The draft attends to the text
around the image only, which can only change how many drafts are accepted (84% after an image), never the output.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 3 hunks across 3 file(s).

Usage: python patches/apply_mtp_pos_jumps_059.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'allow_pos_jumps'

EDITS = {
    os.path.join(tree, "src", "llama-batch.h"): [
        ('''
    uint32_t n_embd;
''',
         '''
public:
    // strixllama: positions may jump forward, as with M-RoPE - an MTP draft context, which never sees a prompt's
    // image tokens (the drafter skips embedding batches), on a model with plain RoPE (Nemotron 3.5 Super)
    bool allow_pos_jumps = false;

private:

    uint32_t n_embd;
'''),
    ],
    os.path.join(tree, "src", "llama-batch.cpp"): [
        ('''    if (n_pos_per_embd > 1) {
''',
         '''    if (n_pos_per_embd > 1 || allow_pos_jumps) {
'''),
    ],
    os.path.join(tree, "src", "llama-context.cpp"): [
        ('''    LLAMA_LOG_INFO("%s: constructing llama_context\\n", __func__);

''',
         '''    LLAMA_LOG_INFO("%s: constructing llama_context\\n", __func__);

    // strixllama: an MTP draft context skips the target's image batches, so its positions jump over them
    balloc->allow_pos_jumps = params.ctx_type == LLAMA_CONTEXT_TYPE_MTP;

'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
