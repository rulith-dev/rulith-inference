#!/usr/bin/env python3
"""0.5.8: the softmax + top-k + normalized weights router kernel as a compile-time instance

The MoE router kernel (softmax, top-k, normalized weights) runs once a layer between large products and its code is
fetched anew each time; the runtime-configured kernel carried every gating path (sigmoid, sqrt-softplus, delayed
softmax) and both argmax paths. The configuration Qwen-Next uses gets an instance of its own with the configuration and
the DPP switch compile-time: 8.45 -> 6.63 us a layer, the same operations. STRIX_TOPK_MOE_SPEC=0: off, -1: the AB side.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 9 hunks across 1 file(s).

Usage: python patches/apply_topk_moe_spec_058.py [tree]
"""
