"""The decode indexer score with each lane taking only its own block's queries (bitwise).

With several conversations the block list is interleaved and k_idx_score_dec ran every query's dot products for the whole wave; k_idx_score_dec3 marks the visible queries per lane first. Same arithmetic, same bits.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 4 hunks across 1 file(s).

Usage: python patches/apply_idx_score_v3_036.py [tree]
"""
