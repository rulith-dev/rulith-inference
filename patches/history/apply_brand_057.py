#!/usr/bin/env python3
"""0.5.7: the fork names itself - Rulith Inference's engine (README, LICENSE, build info, the server's start).

The README's first lines say this branch is Rulith Inference's inference engine and send problems and ideas to that repository; LICENSE keeps the ggml authors' notice and adds the copyright of the changes on this branch, which MIT has every copy carry; llama_print_build_info (--version) and the server's start log name the engine and the repository. No behaviour changes.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 4 hunks across 4 file(s).

Usage: python patches/apply_brand_057.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'Rulith Inference engine'

EDITS = {
    os.path.join(tree, "README.md"): [
        ('''# llama.cpp

''',
         '''# llama.cpp

> **This is the inference engine of [Rulith Inference](https://github.com/rulith-dev/rulith-inference)**, a Windows app
> that runs Qwen3.8-Flash-Next on one AMD Strix Halo machine. Get the app from its
> [releases](https://github.com/rulith-dev/rulith-inference/releases), and report problems and ideas
> [there](https://github.com/rulith-dev/rulith-inference/issues). This branch (`rulith`) is upstream llama.cpp plus the
> patch set that repository keeps in `patches/`, which `bootstrap/` replays onto the pinned upstream revision.
> Everything below is upstream's README.

'''),
    ],
    os.path.join(tree, "LICENSE"): [
        ('''Copyright (c) 2023-2026 The ggml authors

''',
         '''Copyright (c) 2023-2026 The ggml authors
Copyright (c) 2026 Victor Shaw (Rulith Inference: the changes on the rulith branch)

'''),
    ],
    os.path.join(tree, "common", "build-info.cpp.in"): [
        ('''void llama_print_build_info(const char * llama_version, FILE * stream) {
    fprintf(stream, "version: %s (build %d, commit %s)\\n", llama_version, llama_build_number(), llama_commit());
''',
         '''void llama_print_build_info(const char * llama_version, FILE * stream) {
    fprintf(stream, "Rulith Inference engine - https://github.com/rulith-dev/rulith-inference\\n");
    fprintf(stream, "version: %s (build %d, commit %s)\\n", llama_version, llama_build_number(), llama_commit());
'''),
    ],
    os.path.join(tree, "tools", "server", "server.cpp"): [
        ('''    common_params_print_info(params, !is_router_server);

''',
         '''    common_params_print_info(params, !is_router_server);
    SRV_INF("Rulith Inference engine, build %s - https://github.com/rulith-dev/rulith-inference\\n", llama_build_info());

'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
