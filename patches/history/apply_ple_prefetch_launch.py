#!/usr/bin/env python3
"""Launch the PLE row prefetch off the critical path.

The other half of the overlapped PLE gather: qwen4exp hands the next chunk's rows to the reader
while the current chunk is still on the GPU. Only warms the file cache; gathered rows are unchanged.

This half had no working script - apply_hip_ple_probe reports 'already applied' and writes nothing -
so a clean rebuild dropped it.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 3 hunks across 1 file(s).

Usage: python patches/apply_ple_prefetch_launch.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'launch_prefetch'

EDITS = {
    os.path.join(tree, "src", "models", "qwen4exp.cpp"): [
        ('''// the previous chunk is still on the GPU. It only calls posix_fadvise, so a wrong prediction costs nothing but readahead.
''',
         '''// the previous chunk is still on the GPU. Prefetch only warms the file cache; it does not change gathered rows.
'''),
        ('''    std::thread([&pmodel, toks = std::move(toks), n_gram, n_heads, per_gram, eos, n_prev, &hp]() {
''',
         '''    auto prefetch = [reader = pmodel.ple_reader, toks = std::move(toks), n_gram, n_heads, per_gram, eos, n_prev, hp]() {
'''),
        ('''        pmodel.ple_reader->prefetch(idx.data(), (int64_t) idx.size());
    }).detach();
''',
         '''        reader->prefetch(idx.data(), (int64_t) idx.size());
    };
#ifdef _WIN32
    pmodel.ple_reader->launch_prefetch(std::move(prefetch));
#else
    std::thread(std::move(prefetch)).detach();
#endif
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
