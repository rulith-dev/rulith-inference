#!/usr/bin/env python3
"""The dense-input ubatch bound counts the batch's own conversations' cells (issue #10)

Issue #10 (fix by @obsidience): the bound from #2 sized n_kv by the pool's last used cell, so with KV regions one conversation's image ubatches - and with them its greedy output - depended on what other slots held. It now takes the run of cells the graph views for the batch's own conversations (get_kv_window), falling back to the pool without regions or the window.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 2 hunks across 1 file(s).

Usage: python patches/apply_dense_ubatch_own_cells.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'hybrid_idx_dense_n_kv'

EDITS = {
    os.path.join(tree, "src", "llama-memory-hybrid-idx.cpp"): [
        ('''
llama_memory_context_ptr llama_memory_hybrid_idx::init_batch(llama_batch_allocr & balloc, uint32_t n_ubatch, bool embd_all) {
''',
         '''
// strixllama: the cells the dense inputs of this batch span. Under regions the graph views only the run of cells that
// holds the batch's own conversations (llama_kv_cache::get_kv_window), so that run plus the new tokens - not the pool up
// to its last used cell - is what the bound below has to cover. Sizing it by the pool made one conversation's ubatch
// split, and with it its greedy output, depend on what the other slots held and had held.
static uint64_t hybrid_idx_dense_n_kv(const llama_kv_cache & kv, const llama_batch & batch) {
    const auto & cells = kv.get_cells(0);
    const uint64_t pool = (uint64_t) cells.used_max_p1() + batch.n_tokens;

    static const bool window = [] {
        const char * e = getenv("LLAMA_KV_WINDOW");
        return !e || atoi(e) != 0;
    }();
    if (!window || !kv.get_regions()) {
        return pool;
    }

    std::bitset<LLAMA_MAX_SEQ> seen;
    int64_t lo = INT64_MAX;
    int64_t hi = -1;
    for (int32_t i = 0; i < batch.n_tokens; ++i) {
        for (int32_t k = 0; k < batch.n_seq_id[i]; ++k) {
            const llama_seq_id s = batch.seq_id[i][k];
            if (s < 0 || s >= LLAMA_MAX_SEQ || seen.test(s)) {
                continue;
            }
            seen.set(s);
            const int64_t c0 = cells.seq_cell_min(s);
            if (c0 >= 0) {
                lo = std::min(lo, c0);
                hi = std::max(hi, cells.seq_cell_max(s) + 1);
            }
        }
    }

    // the window is padded to 256 cells (get_kv_window)
    const uint64_t own = (hi > lo ? (uint64_t) (hi - lo) : 0) + batch.n_tokens + 256;
    return std::min(pool, own);
}

llama_memory_context_ptr llama_memory_hybrid_idx::init_batch(llama_batch_allocr & balloc, uint32_t n_ubatch, bool embd_all) {
'''),
        ('''        const uint64_t n_kv = (uint64_t) get_mem_attn()->get_cells(0).used_max_p1() + balloc.get_n_tokens();
''',
         '''        const uint64_t n_kv = hybrid_idx_dense_n_kv(*get_mem_attn(), balloc.get_batch());
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
