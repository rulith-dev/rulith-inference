#!/usr/bin/env python3
"""0.5.8: measurement only - STRIX_AB_MIN_NODES and STRIX_GPU_TIMELINE_PRINT

Measurement only. STRIX_AB_MIN_NODES=n: the STRIX_AB step medians count only graphs of at least n nodes (with MTP
1000 picks the verify passes, so a median is a whole MTP step). STRIX_GPU_TIMELINE_PRINT=n: a table every n readings
(default 8; 1 for a single prompt).

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 2 hunks across 1 file(s).

Usage: python patches/apply_dev_measure_058.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'STRIX_AB_MIN_NODES'

EDITS = {
    os.path.join(tree, "ggml", "src", "ggml-cuda", "ggml-cuda.cu"): [
        ('''    if (++a.readings % 8 != 0) {
''',
         '''    // STRIX_GPU_TIMELINE_PRINT=n: a table every n readings (default 8; 1 for a single prompt)
    static const int print_every = getenv("STRIX_GPU_TIMELINE_PRINT") ? std::max(1, atoi(getenv("STRIX_GPU_TIMELINE_PRINT"))) : 8;
    if (++a.readings % print_every != 0) {
'''),
        ('''    if (every <= 0 || cgraph->n_nodes < 64 || ggml_nrows(cgraph->nodes[0]) >= 64) {
''',
         '''    // STRIX_AB_MIN_NODES=n: only graphs of at least n nodes count (with MTP: the verify passes, a step apart)
    static const int min_nodes = getenv("STRIX_AB_MIN_NODES") ? atoi(getenv("STRIX_AB_MIN_NODES")) : 64;
    if (every <= 0 || cgraph->n_nodes < min_nodes || ggml_nrows(cgraph->nodes[0]) >= 64) {
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
