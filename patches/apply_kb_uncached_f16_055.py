#!/usr/bin/env python3
"""0.5.5: without the block-key cache the indexer scores with F16-rounded keys too (issue #16).

With the block-key cache wired in, build_qsa_top_k scores blocks with the keys read back from the F16 cache (a rebuild
graph too, since apply_qsa_kb_rebuild_f16). Without it it scored with the pooled keys just computed, in F32. The cache
is left out when it is switched off (LLAMA_QSA_BLOCK_KEY_CACHE=0), with several KV streams, for an image ubatch, and -
through kb_pos_dup - for every text ubatch after the server has seen one image, until all its conversations are
cleared. So once a server had seen an image, text above the sparse-attention threshold came out slightly different
from a fresh server's: block choices on a knife edge flipped and greedy output changed (issue #16, reported with this
change). The uncached keys are now rounded to F16 and back. Measured on an 11K-token prompt, greedy with top-5
log-probabilities: before, the same request after an image differed from token 83 (log-probabilities from position 1),
as with the cache off; after, before and after an image, cache on and off, and the default without the change all
bit-identical. Two casts on a blocks x 128 tensor per indexer layer, only in the uncached branch. The text path with
the cache - every graph before an image - is unchanged.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 1 hunks across 1 file(s).

Usage: python patches/apply_kb_uncached_f16_055.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'came out different from'

EDITS = {
    os.path.join(tree, "src", "models", "qwen4exp.cpp"): [
        ('''            pooled = ggml_reshape_3d(ctx0, pooled, idx_dim, n_blocks, n_stream);
        }
''',
         '''            pooled = ggml_reshape_3d(ctx0, pooled, idx_dim, n_blocks, n_stream);
        } else {
            // without the cache - switched off, several streams, an image ubatch, or any text after an image
            // (kb_pos_dup) - the keys are rounded to F16 too: the block choice, and the text, came out different from
            // a fresh server's once the server had seen one image (issue #16)
            pooled = ggml_cast(ctx0, ggml_cast(ctx0, pooled, GGML_TYPE_F16), GGML_TYPE_F32);
        }
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
