#!/usr/bin/env python3
"""The run-based sparse-attention inputs reuse their buffers and set the membership rows one-hot.

set_input_qsa_run (0.3.4) built its outputs in vectors allocated on every call - with eight conversations at 40K each about 4 MB a step, the membership rows alone 650K floats - and set each block's membership by comparing its sequence with every slot. The vectors are now members kept from call to call, so a step reuses the last one's memory, and each run's slot is found once, a block's row then written at that slot. The same inputs, byte for byte (STRIX_QSA_RUN=2 compares them with the scan's): the host time of the step's QSA inputs 1.7-1.8 -> 0.8-1.05 ms at eight conversations.

Generated by tools/make_patch_script.py from the tree it must reproduce, so every anchor is
unique by construction. 4 hunks across 2 file(s).

Usage: python patches/apply_qsa_run_buffers_035.py [tree]
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "llama.cpp")
MARKER = 'run_slot'

EDITS = {
    os.path.join(tree, "src", "llama-memory-hybrid-idx.h"): [
        ('''    };
    bool set_input_qsa_run(qsa_run_inputs & out, ggml_tensor * cell_blk, ggml_tensor * blk_cells, ggml_tensor * blk_pos,
''',
         '''    };
    // kept from one call to the next, so a step's inputs reuse the last one's memory (eight conversations at 40K: ~4 MB)
    mutable qsa_run_inputs       run_ri;
    mutable std::vector<int32_t> run_blk_run, run_blk_pb;
    bool set_input_qsa_run(qsa_run_inputs & out, ggml_tensor * cell_blk, ggml_tensor * blk_cells, ggml_tensor * blk_pos,
'''),
    ],
    os.path.join(tree, "src", "llama-memory-hybrid-idx.cpp"): [
        ('''    std::vector<int32_t> blk_run;   // per block: its run
    std::vector<int32_t> blk_pb;    // and its bucket
''',
         '''    std::vector<int32_t> & blk_run = run_blk_run;   // per block: its run
    std::vector<int32_t> & blk_pb  = run_blk_pb;    // and its bucket
    blk_run.clear();
    blk_pb.clear();
    blk_run.reserve(n_blocks);
    blk_pb.reserve(n_blocks);
'''),
        ('''        for (int64_t b = 0; b < n_bid; ++b) {
            const llama_seq_id s = runs[blk_run[b]].s;
            for (int64_t sl = 0; sl < n_slots; ++sl) {
                if (ubatch->seq_id_unq[sl] == s) {
                    out.seq_blk[b*n_slots + sl] = 1.0f;
                }
''',
         '''        // each run's slot, once: a block's row is one-hot (its sequence is one of the ubatch's, each in one slot)
        std::vector<int64_t> run_slot(runs.size(), -1);
        for (size_t k = 0; k < runs.size(); ++k) {
            for (int64_t sl = 0; sl < n_slots; ++sl) {
                if (ubatch->seq_id_unq[sl] == runs[k].s) {
                    run_slot[k] = sl;
                }
            }
        }
        for (int64_t b = 0; b < n_bid; ++b) {
            const int64_t sl = run_slot[blk_run[b]];
            if (sl >= 0) {
                out.seq_blk[b*n_slots + sl] = 1.0f;
'''),
        ('''    qsa_run_inputs ri;
''',
         '''    qsa_run_inputs & ri = run_ri;
    ri.clear_from.clear();
    ri.set_stale = false;
'''),
    ],
}


def main():
    texts = {p: io.open(p, encoding="utf-8").read() for p in EDITS}
    if any(MARKER in t for t in texts.values()):
        print("already applied")
        return
    for p, pairs in EDITS.items():
        for old, new in pairs:
            if texts[p].count(old) != 1:
                sys.exit("anchor found %d times, expected once, in %s" % (texts[p].count(old), p))
            texts[p] = texts[p].replace(old, new, 1)
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    print("patched", ", ".join(os.path.basename(p) for p in EDITS))


if __name__ == "__main__":
    main()
